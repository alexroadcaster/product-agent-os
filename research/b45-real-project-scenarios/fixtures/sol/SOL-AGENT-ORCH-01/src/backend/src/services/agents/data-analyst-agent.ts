import { AgentNode, AgentState, getAgentSystemInstructions } from '../orchestrator';
import { runProAgent } from '../ai';
import { ToolDispatcher } from '../tools/dispatcher';
import { agentRegistry } from '../agent-registry';

export class DataAnalystAgent implements AgentNode {
    name = 'Ben (Lead Data Analyst)';
    role = 'data_analyst' as const;

    async execute(state: AgentState): Promise<AgentState> {
        const userMessage = state.messages.find(m => m.role === 'user')?.content || '';
        const architecture = state.artifacts.architecture || '';
        const tasks = state.tasks || [];

        const profile = agentRegistry.getProfile(this.role);
        const systemPrompt = profile ? profile.systemPrompt : `You are Ben, the Lead Data Analyst for the SOL ecosystem.
You operate on a strict 4-Step Universal Principle: Philosophy, Logic, Strategy, Execution.

[Philosophy]: "Data is the lifeblood of the system. We focus on fast, efficient retrieval, scalable database design, and robust data pipelines. We build with PostgreSQL best practices, avoiding N+1 queries missing indexes, and unoptimized scans."
[Logic]: We analyze the Architecture and the execution tasks generated by the Developer. We must identify potential database bottlenecks early, design proper B-tree or composite indexes, and propose necessary ETL structures. Think in EXPLAIN ANALYZE terms.
[Strategy]: Review the tasks and architecture. Produce a "Database & Data Pipeline Plan". Do not over-engineer; focus on immediate commercial MVP needs, but ensure the foundation won't collapse under load.`;

        const prompt = `
    ${systemPrompt}
    
    ${getAgentSystemInstructions(state)}

    [Execution]:
    Output ONLY a valid JSON object in the text output. No markdown wrapping.
    
    {
      "philosophy": "Statement of your core belief regarding this project's data",
      "logic": "Step-by-step reasoning on data structures, query patterns, and indexing",
      "strategy": "Actionable plan for database design and optimization",
      "execution": {
        "reply": "A concise message explaining your data plan and passing control to the Optimizer",
        "databasePlan": "Detailed markdown string containing your schema notes, indexing strategy, and key optimizations"
      }
    }

    Context:
    Architecture:
    ${architecture}

    Tasks planned:
    ${JSON.stringify(tasks, null, 2)}
    `;

        try {
            const responseText = await runProAgent(prompt);

            const cleanJson = responseText.replace(/^```json/gm, '').replace(/^```/gm, '').trim();
            const parsed = JSON.parse(cleanJson);

            console.log(`[data-analyst] Philosophy: ${parsed.philosophy}`);
            console.log(`[data-analyst] Logic: ${parsed.logic}`);
            console.log(`[data-analyst] Strategy: ${parsed.strategy}`);

            const execution = parsed.execution || {};

            state.messages.push({
                id: crypto.randomUUID(),
                role: 'assistant',
                agentName: 'Ben (Lead Data Analyst)',
                content: execution.reply || "Thinking...",
                timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
            });

            if (execution.databasePlan) {
                state.artifacts = state.artifacts || {};
                state.artifacts.databasePlan = execution.databasePlan;
            }

            console.log(`[data-analyst]: Handing off to Optimizer Agent...`);
            state.currentRole = 'optimizer';
            state.awaitingUserApproval = false;

        } catch (e) {
            console.error("[data-analyst] Failed to process:", e);
            state.messages.push({
                id: crypto.randomUUID(),
                role: 'assistant',
                agentName: 'Ben (Lead Data Analyst)',
                content: "I encountered an error analyzing the data requirements. Please check my logs.",
                timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
            });
            state.awaitingUserApproval = true;
        }

        return state;
    }
}
