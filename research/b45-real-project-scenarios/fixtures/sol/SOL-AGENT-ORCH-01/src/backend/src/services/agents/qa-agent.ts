import { AgentNode, AgentState, getAgentSystemInstructions } from '../orchestrator';
import { runProAgent } from '../ai';
import { ToolDispatcher } from '../tools/dispatcher';
import { agentRegistry } from '../agent-registry';

export class QaAgent implements AgentNode {
    name = 'Eve (Lead Quality Assurance)';
    role = 'qa' as const;

    async execute(state: AgentState): Promise<AgentState> {
        const userMessage = state.messages.find(m => m.role === 'user')?.content || '';
        const architecture = state.artifacts.architecture || '';
        const tasks = state.tasks || [];

        const profile = agentRegistry.getProfile(this.role);
        const systemPrompt = profile ? profile.systemPrompt : `You are Eve, the Lead Quality Assurance (QA) engineer for the SOL ecosystem.
You operate on a strict 4-Step Universal Principle: Philosophy, Logic, Strategy, Execution.

[Philosophy]: "Trust, but verify." Every feature must have a clear testing strategy. Code without tests is broken by design.
[Logic]: We analyze the Architecture and the execution tasks generated by the Developer. We determine the most critical paths and propose Unit, Integration, and E2E testing patterns.
[Strategy]: Formulate a comprehensive "Automated Testing Strategy". Ensure it maps directly to the tasks and architectural components.`;

        const prompt = `
    ${systemPrompt}
    
    ${getAgentSystemInstructions(state)}

    [Execution]:
    Output ONLY a valid JSON object in the text output. No markdown wrapping.
    
    {
      "philosophy": "Statement of your core belief regarding system quality",
      "logic": "Step-by-step reasoning on test coverage and edge cases",
      "strategy": "Actionable plan for writing and running the tests",
      "execution": {
        "reply": "A concise message explaining your testing strategy and passing control to Security",
        "testingPlan": "Detailed markdown string containing your testing framework choices, critical test cases, and Mocks/Stubs strategy"
      }
    }

    Context:
    Architecture & Plans so far:
    ${architecture}

    Tasks planned:
    ${JSON.stringify(tasks, null, 2)}
    `;

        try {
            const responseText = await runProAgent(prompt);

            const cleanJson = responseText.replace(/^```json/gm, '').replace(/^```/gm, '').trim();
            const parsed = JSON.parse(cleanJson);

            console.log(`[qa] Philosophy: ${parsed.philosophy}`);
            console.log(`[qa] Logic: ${parsed.logic}`);
            console.log(`[qa] Strategy: ${parsed.strategy}`);

            const execution = parsed.execution || {};

            state.messages.push({
                id: crypto.randomUUID(),
                role: 'assistant',
                agentName: 'Eve (Lead QA)',
                content: execution.reply || "Thinking about test coverage...",
                timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
            });

            if (execution.testingPlan) {
                state.artifacts = state.artifacts || {};
                state.artifacts.testingPlan = execution.testingPlan;
            }

            console.log(`[qa]: Handing off to Security Agent...`);
            state.currentRole = 'security';
            state.awaitingUserApproval = false;

        } catch (e) {
            console.error("[qa] Failed to process:", e);
            state.messages.push({
                id: crypto.randomUUID(),
                role: 'assistant',
                agentName: 'Eve (Lead QA)',
                content: "I encountered an error analyzing the testing requirements. Please check my logs.",
                timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
            });
            state.awaitingUserApproval = true;
        }

        return state;
    }
}
