export type Role = 'router' | 'po' | 'ba' | 'marketer' | 'designer' | 'architect' | 'developer' | 'data_analyst' | 'optimizer' | 'qa' | 'security' | 'context_manager';

export type TaskType = 'Epic' | 'Story' | 'Task' | 'SubTask' | 'Bug' | 'Idea';
export type TaskStatus = 'To Do' | 'In Progress' | 'Review' | 'Done';

export interface Task {
  projectId: string;
  projectName: string;
  id: string;
  title: string;
  type: TaskType;
  status: TaskStatus;
  assignees: string[];
  author: string;
  description: string;
  artifacts: string[];
  affectedFiles: string[];
  dependencies: string[];
  agentThoughts: string[];
  plannedTime?: string | number;
  actualTime?: string | number;
}

export interface Message {
  id: string;
  role: 'user' | 'assistant' | 'system';
  agentName?: string;
  content: string;
  timestamp: string;
}

export interface Artifacts {
  prd?: string;
  marketResearch?: string;
  gtmStrategy?: string;
  designSystem?: string;
  architecture?: string;
  databasePlan?: string;
  optimizationPlan?: string;
  testingPlan?: string;
  securityPlan?: string;
  executionGraph?: string;
}

export interface AgentState {
  // Current active role
  currentRole: Role;

  // The conversation history specific to the current session/task
  messages: Message[];

  // Structured artifacts that are passed between agents (Artefact-Driven MAS)
  artifacts: Artifacts;

  // Tasks generated by Architect/Dev
  tasks: Task[];

  // Control flag: should we stop and wait for user input?
  awaitingUserApproval: boolean;

  // Signal to interrupt the agent chain
  isPaused?: boolean;

  // The very first prompt from the user used to enforce language consistency
  initialPrompt?: string;
}

/**
 * Base Agent interface.
 * Each specialized agent will implement this.
 */
export interface AgentNode {
  name: string;
  role: Role;
  execute(state: AgentState): Promise<AgentState>;
}

/**
 * Helper to get shared system instructions for all agents.
 */
export function getAgentSystemInstructions(state: AgentState): string {
  const languageInstruction = state.initialPrompt
    ? `CRITICAL LANGUAGE RULE (HIGHEST PRIORITY): You MUST respond ONLY in the same language as the user's initial message. The user wrote: "${state.initialPrompt}". Detect the language of that message and use EXACTLY that language for your ENTIRE response — every word, every sentence, including technical explanations. If the user wrote in Russian, respond in Russian. If in English, respond in English. NEVER switch languages mid-conversation. This rule overrides all other instructions.\n`
    : '';
  const handoffInstruction = `If you are passing control to another agent, you MUST explicitly state in your reply exactly who you are handing off to (by name and role) and what you expect them to do. Do not just say "passing control", but speak to the user, e.g., "I'm handing this over to Leo the Architect to design the system."\n`;

  return `\n    SYSTEM CAPABILITIES & CONSTRAINTS:\n    ${languageInstruction}    ${handoffInstruction}\n    REMINDER: Your reply text MUST be in the same language as the user's first message. This is non-negotiable.`;
}

/**
 * The State Machine Orchestrator.
 * Manages the transition of state between different specialized agents.
 */
export class Orchestrator {
  private agents: Map<Role, AgentNode> = new Map();

  registerAgent(agent: AgentNode) {
    this.agents.set(agent.role, agent);
  }

  /**
   * Processes a new user message through the state machine.
   * Accepts an optional onStateChange callback to emit progress to the UI.
   */
  async processMessage(
    state: AgentState,
    userMessage: Message,
    onStateChange?: (state: AgentState) => void
  ): Promise<AgentState> {
    // 1. Add user message to state
    state.messages.push(userMessage);

    // 2. If we don't know who should handle this, start with the Router
    if (!state.currentRole) {
      state.currentRole = 'router';
    }

    // NEW: Explicit routing via @mention (e.g., "@developer please do this")
    if (userMessage.role === 'user') {
      const mentionMatch = userMessage.content.match(/(?:^|\s)@([a-zA-Z_]+)\b/);
      if (mentionMatch) {
        const mentionedRole = mentionMatch[1].toLowerCase() as Role;
        if (this.agents.has(mentionedRole)) {
          state.currentRole = mentionedRole;
        }
      }
    }

    if (!state.initialPrompt) {
      state.initialPrompt = userMessage.content;
    }

    let nextState = state;
    // Always clear pause state when a new message is explicitly sent
    nextState.isPaused = false;
    let keepRunning = true;

    // 3. Execution Loop (ReAct / Graph loop)
    // We run until the agent says they are awaiting user approval (i.e., they need a reply from the real USER).
    while (keepRunning) {
      const activeAgent = this.agents.get(nextState.currentRole);

      if (!activeAgent) {
        throw new Error(`Agent for role ${nextState.currentRole} not found!`);
      }

      console.log(`[orchestrator]: Executing node: ${activeAgent.name} (Role: ${activeAgent.role})`);

      // The agent executes its logic, potentially modifying the state, creating artifacts, 
      // adding assistant messages, and changing the 'currentRole' to pass the baton.
      nextState = await activeAgent.execute(nextState);

      // Fire callback to update UI immediately with new messages/artifacts
      if (onStateChange) {
        onStateChange(nextState);
      }

      // If the state is marked as paused, or awaiting user approval
      if (nextState.isPaused) {
        keepRunning = false;
        console.log(`[orchestrator]: Session paused mid-flight.`);
        // We do NOT set awaitingUserApproval = true here necessarily, as they might resume
        // But the front end will stop showing "thinking".
      } else if (nextState.awaitingUserApproval) {
        keepRunning = false;
      }

      // Safety check: if the role didn't change and we are still running, 
      // we must break to prevent infinite loops without user input.
      // (This assumes an agent either replies to user OR passes baton).
      if (nextState.currentRole === activeAgent.role && !nextState.awaitingUserApproval) {
        // Force stop if the agent didn't explicity hand off or pause
        nextState.awaitingUserApproval = true;
        keepRunning = false;
      }
    }

    return nextState;
  }
}

// Global orchestrator instance
export const orchestrator = new Orchestrator();
